def s_orders():
    rules = [("order_id", "required string, 'ORD-' followed by 6 digits"),
             ("customer_id", "required integer"),
             ("order_date", "required date, YYYY-MM-DD"),
             ("ship_date", "optional date, YYYY-MM-DD, not before order_date"),
             ("status", "required, one of pending, shipped, delivered, cancelled"),
             ("quantity", "required integer, 1 to 100"),
             ("unit_price", "required number, greater than 0"),
             ("total", "required number, must equal quantity x unit_price"),
             ("notes", "optional free text")]

    def valid(r):
        od = d(r)
        q, p = r.randrange(1, 60), round(r.uniform(2, 400), 2)
        status = C.pick(r, ["pending", "shipped", "delivered", "cancelled"])
        return {"order_id": f"ORD-{r.randrange(100000, 999999)}", "customer_id": r.randrange(1000, 99999),
                "order_date": od, "ship_date": None if status in ("pending", "cancelled") else add_days(od, r.randrange(0, 9)),
                "status": status, "quantity": q, "unit_price": p, "total": round(q * p, 2)}

    def set_(k, v):
        return lambda r, x: x.__setitem__(k, v(r, x) if callable(v) else v)
    corrupt = {
        "missing_value": [lambda r, x: x.pop("customer_id"), set_("order_date", None), set_("order_id", ""),
                          lambda r, x: x.pop("status")],
        "wrong_type": [set_("quantity", lambda r, x: str(x["quantity"])), set_("unit_price", lambda r, x: f"${x['unit_price']}"),
                       set_("customer_id", lambda r, x: str(x["customer_id"])), set_("quantity", "twelve")],
        "out_of_range": [lambda r, x: (x.__setitem__("quantity", C.pick(r, [0, -2, 250, 1000])),
                                       x.__setitem__("total", round(x["quantity"] * x["unit_price"], 2))),
                         set_("status", lambda r, x: C.pick(r, ["lost", "returned", "on_hold"])),
                         lambda r, x: (x.__setitem__("unit_price", -x["unit_price"]), x.__setitem__("total", -x["total"]))],
        "bad_format": [set_("order_date", lambda r, x: us_date(x["order_date"])),
                       set_("order_id", lambda r, x: x["order_id"].replace("ORD-", C.pick(r, ["ORD", "ord-", "OR-"]))),
                       set_("order_id", lambda r, x: x["order_id"] + "7")],
        "inconsistent": [lambda r, x: (x.__setitem__("status", "shipped"), x.__setitem__("ship_date", add_days(x["order_date"], -r.randrange(2, 20)))),
                         set_("total", lambda r, x: round(x["total"] + C.pick(r, [10, 25.5, 100, x["unit_price"]]), 2))],
    }
    return {"table": "orders", "rules": rules, "text_field": "notes", "valid": valid, "corrupt": corrupt,
            "ddl_checks": ["CHECK (total = quantity * unit_price)", "CHECK (ship_date IS NULL OR ship_date >= order_date)"]}


