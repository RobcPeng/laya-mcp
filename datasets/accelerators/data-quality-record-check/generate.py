def render_schema(rng, sc):
    if rng.random() < 0.5:
        lines = [f"Table {sc['table']}:"] + [f"- {f}: {t}" for f, t in sc["rules"]]
        return "\n".join(lines)
    lines = [f"{sc['table']} rules"] + [f"{f} -- {t}" for f, t in sc["rules"]] + sc["ddl_checks"]
    return "\n".join(lines)


def render_record(rng, rec):
    if rng.random() < 0.5:
        return json.dumps(rec, ensure_ascii=False)
    return json.dumps(rec, ensure_ascii=False, separators=(",", ":"))


def build(rng):
    examples = []
    for fam, mk in SCHEMAS.items():
        sc = mk()
        plan = [None] * VALID_PER_SCHEMA + [iss for iss in ISSUES for _ in range(PER_ISSUE)]
        for k, issue in enumerate(plan):
            rec = sc["valid"](rng)
            pii = rng.random() < 0.38
            txt = free_text(rng, pii)
            if txt or rng.random() < 0.5:          # optional field: present, empty string, null, or absent
                rec[sc["text_field"]] = txt if txt else C.pick(rng, ["", None])
            if issue:
                fns = sc["corrupt"][issue]
                fns[k % len(fns)](rng, rec)
            examples.append({
                "family": fam, "group": fam,
                "state": {"schema": render_schema(rng, sc), "record": render_record(rng, rec)},
                "gold": {"is_valid": issue is None, "issue": issue or "none", "pii_in_text": pii},
            })
    return examples


def main():
    rng = C.rng_for(NAME, SEED)
    splits = C.write_dataset(NAME, build(rng), HERE, PREFIX, seed=SEED, test_families=TEST_FAMILIES)
    C.summary(NAME, splits)
    return splits


