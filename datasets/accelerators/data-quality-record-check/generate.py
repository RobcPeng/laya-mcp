def free_text(rng, pii):
    if pii:
        t = C.pick(rng, PII_TEXT)(rng)
        if rng.random() < 0.4:
            t = C.pick(rng, PLAIN_TEXT) + " " + t
        return t.strip()
    if rng.random() < 0.55:
        t = C.pick(rng, LOOKALIKE_TEXT)(rng)
        if rng.random() < 0.3:
            t = t + " " + C.pick(rng, PLAIN_TEXT)
        return t.strip()
    return C.pick(rng, PLAIN_TEXT)


