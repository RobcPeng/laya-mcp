# ------------------------------------------------------------------ small value helpers

def d(rng, y0=2023, y1=2025):
    return f"{rng.randrange(y0, y1 + 1)}-{rng.randrange(1, 13):02d}-{rng.randrange(1, 29):02d}"


def add_days(date, n):
    y, m, dd = (int(x) for x in date.split("-"))
    dd += n
    while dd > 28:                       # 28-day months keep the arithmetic trivially valid
        dd -= 28
        m += 1
        if m > 12:
            m, y = 1, y + 1
    while dd < 1:
        dd += 28
        m -= 1
        if m < 1:
            m, y = 12, y - 1
    return f"{y}-{m:02d}-{dd:02d}"


def ts(rng, date=None):
    return f"{date or d(rng)}T{rng.randrange(0, 24):02d}:{rng.randrange(0, 60):02d}:{rng.randrange(0, 60):02d}Z"


def us_date(iso):
    y, m, dd = iso[:10].split("-")
    return f"{m}/{dd}/{y}"


def hexid(rng, n):
    return "".join(C.pick(rng, "0123456789abcdef") for _ in range(n))


